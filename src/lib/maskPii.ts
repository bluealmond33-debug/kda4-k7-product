/**
 * 화면에 그리기 직전 개인정보 가리기 — **표시 단계 안전망.**
 *
 * 왜 프론트에도 두는가: 이 제품의 주장은 "AI는 대화 내용만 보고 민감정보 원문엔 손대지
 * 않는다"다. 그런데 전사는 고객이 말한 그대로 흘러오므로, 고객이 생년월일이나 계좌번호를
 * 말하면 그 숫자가 상담사 화면에 남는다. 백엔드(pii-service·스트리밍 인라인 마스킹)가 1차로
 * 가리지만, **대본 데모(백엔드 없이 시연)에는 그 경로가 없다.** 실제로 시연 화면의 근거
 * 발화에 "890315입니다"가 그대로 찍혀 있었다 — 은행 심사에서 가장 먼저 지적될 자리다.
 * 그래서 그리는 쪽에서 한 번 더 막는다. 두 겹이면 어느 경로로 와도 화면에는 남지 않는다.
 *
 * 원칙 — **과하게 가리지 않는다.** 지우면 상담사가 근거를 잃는다:
 *  · 6자리 이상 숫자 뭉치만 가린다(생년월일 6·8자리 · 계좌 · 카드 · 주민번호).
 *  · 앞 2자리는 남긴다 — 상담사가 "그 번호 맞다"를 대조할 실마리는 있어야 한다.
 *  · 금액·기간·개수는 건드리지 않는다(30만원 · 3개월 · 2건). 자릿수가 적고, 가리면
 *    통화 내용 자체가 안 읽힌다.
 *  · 카드·계좌는 구분자(-)가 섞여도 한 뭉치로 본다.
 */

/** 숫자 뒤에 붙으면 '민감정보가 아니다'로 보는 단위 — 금액·기간·수량 */
const SAFE_UNIT = /^\s*(원|만원|천원|억|만|개월|개|건|번|명|년|월|일|시|분|초|%|퍼센트|회|층|호)/;

/** 자리를 가린 문자열 — 앞 2자리만 남기고 나머지는 * (구분자는 그대로 둔다) */
function veil(run: string): string {
  let shown = 0;
  return run.replace(/\d/g, () => (shown++ < 2 ? run[run.search(/\d/) + shown - 1] : "*"));
}

/**
 * 전사·요약 등 '고객이 말한 문장'을 화면용으로 가린다.
 * 마스킹할 게 없으면 원문을 그대로 돌려준다(불필요한 문자열 생성 없음).
 */
export function maskPii(text: string): string {
  if (!text) return text;
  // 숫자 6개 이상이 든 뭉치(중간에 - 나 공백 하나까지 허용)
  return text.replace(/\d[\d\s-]{4,}\d/g, (run, at: number) => {
    const digits = run.replace(/\D/g, "");
    if (digits.length < 6) return run;
    // 뒤에 금액·기간 단위가 붙으면 민감정보가 아니다
    if (SAFE_UNIT.test(text.slice(at + run.length))) return run;
    return veil(run);
  });
}
