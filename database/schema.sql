CREATE TABLE routing_recommendations (
    routing_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL,
    recommended_department_id bigint NOT NULL,
    recommended_counselor_id bigint,
    recommendation_rank smallint NOT NULL,
    confidence numeric(5,4) NOT NULL,
    rationale text NOT NULL,
    selected boolean NOT NULL DEFAULT false,
    model_name text NOT NULL,
    model_version text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT routing_recommendations_session_fk
        FOREIGN KEY (session_id) REFERENCES consultation_sessions (session_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT routing_recommendations_department_fk
        FOREIGN KEY (recommended_department_id) REFERENCES departments (department_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT routing_recommendations_counselor_department_fk
        FOREIGN KEY (recommended_counselor_id, recommended_department_id)
        REFERENCES counselors (counselor_id, department_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT routing_recommendations_rank_chk
        CHECK (recommendation_rank > 0),
    CONSTRAINT routing_recommendations_confidence_chk
        CHECK (confidence BETWEEN 0 AND 1),
    CONSTRAINT routing_recommendations_rationale_not_blank_chk
        CHECK (btrim(rationale) <> ''),
    CONSTRAINT routing_recommendations_model_not_blank_chk
        CHECK (btrim(model_name) <> '' AND btrim(model_version) <> ''),
    CONSTRAINT routing_recommendations_session_rank_uk
        UNIQUE (session_id, recommendation_rank)
);

CREATE TABLE access_logs (
    access_log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    counselor_id bigint NOT NULL,
    customer_id bigint NOT NULL,
    session_id bigint,
    information_scope text NOT NULL,
    action_type text NOT NULL DEFAULT 'view',
    access_purpose text NOT NULL,
    result_status text NOT NULL DEFAULT 'success',
    request_id text,
    source_ip inet,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT access_logs_counselor_fk
        FOREIGN KEY (counselor_id) REFERENCES counselors (counselor_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT access_logs_customer_fk
        FOREIGN KEY (customer_id) REFERENCES customers (customer_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT access_logs_session_customer_fk
        FOREIGN KEY (session_id, customer_id)
        REFERENCES consultation_sessions (session_id, customer_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT access_logs_scope_chk
        CHECK (information_scope IN (
            'customer_basic',
            'consultation_history',
            'customer_cautions',
            'utterances',
            'model_analysis_results',
            'ai_consultation_cards',
            'routing_recommendations'
        )),
    CONSTRAINT access_logs_action_chk
        CHECK (action_type IN ('view', 'export', 'create', 'update')),
    CONSTRAINT access_logs_purpose_not_blank_chk
        CHECK (btrim(access_purpose) <> ''),
    CONSTRAINT access_logs_result_chk
        CHECK (result_status IN ('success', 'denied', 'error')),
    CONSTRAINT access_logs_immutable_timestamps_chk
        CHECK (updated_at = created_at)
);

