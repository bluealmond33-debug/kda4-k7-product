BEGIN;

CREATE TABLE departments (
    department_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code text NOT NULL UNIQUE,
    department_name text NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT departments_code_format_chk
        CHECK (department_code ~ '^[a-z][a-z0-9_]*$'),
    CONSTRAINT departments_name_not_blank_chk
        CHECK (btrim(department_name) <> '')
);

CREATE TABLE customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_number text NOT NULL UNIQUE,
    full_name_masked text NOT NULL,
    phone_masked text NOT NULL,
    phone_lookup_hash text NOT NULL UNIQUE,
    account_number_masked text,
    account_lookup_hash text UNIQUE,
    birth_year smallint,
    birth_date_masked text,
    customer_status text NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT customers_number_format_chk
        CHECK (customer_number ~ '^[A-Z0-9_-]{6,30}$'),
    CONSTRAINT customers_name_masked_chk
        CHECK (btrim(full_name_masked) <> '' AND position('*' IN full_name_masked) > 0),
    CONSTRAINT customers_phone_masked_chk
        CHECK (position('*' IN phone_masked) > 0),
    CONSTRAINT customers_phone_hash_chk
        CHECK (phone_lookup_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT customers_account_pair_chk
        CHECK (
            (account_number_masked IS NULL AND account_lookup_hash IS NULL)
            OR (
                account_number_masked IS NOT NULL
                AND account_lookup_hash IS NOT NULL
                AND position('*' IN account_number_masked) > 0
                AND account_lookup_hash ~ '^[0-9a-f]{64}$'
            )
        ),
    CONSTRAINT customers_birth_year_chk
        CHECK (birth_year IS NULL OR birth_year BETWEEN 1900 AND 2100),
    CONSTRAINT customers_birth_date_masked_chk
        CHECK (birth_date_masked IS NULL OR position('*' IN birth_date_masked) > 0),
    CONSTRAINT customers_status_chk
        CHECK (customer_status IN ('active', 'inactive', 'dormant'))
);

CREATE TABLE counselors (
    counselor_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    counselor_code text NOT NULL UNIQUE,
    counselor_name text NOT NULL,
    department_id bigint NOT NULL,
    employment_status text NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT counselors_department_fk
        FOREIGN KEY (department_id) REFERENCES departments (department_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT counselors_code_format_chk
        CHECK (counselor_code ~ '^[A-Z0-9_-]{4,30}$'),
    CONSTRAINT counselors_name_not_blank_chk
        CHECK (btrim(counselor_name) <> ''),
    CONSTRAINT counselors_status_chk
        CHECK (employment_status IN ('active', 'leave', 'inactive')),
    CONSTRAINT counselors_id_department_uk
        UNIQUE (counselor_id, department_id)
);

CREATE TABLE counselor_permissions (
    permission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    counselor_id bigint NOT NULL,
    permission_scope text NOT NULL,
    access_level text NOT NULL,
    granted_reason text NOT NULL,
    granted_by bigint,
    valid_from timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_until timestamptz,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT counselor_permissions_counselor_fk
        FOREIGN KEY (counselor_id) REFERENCES counselors (counselor_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT counselor_permissions_granted_by_fk
        FOREIGN KEY (granted_by) REFERENCES counselors (counselor_id)
        ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT counselor_permissions_scope_chk
        CHECK (permission_scope IN (
            'customer_basic',
            'consultation_history',
            'customer_cautions',
            'utterances',
            'model_analysis_results',
            'ai_consultation_cards',
            'routing_recommendations',
            'access_logs'
        )),
    CONSTRAINT counselor_permissions_level_chk
        CHECK (access_level IN ('masked_read', 'read', 'manage')),
    CONSTRAINT counselor_permissions_reason_not_blank_chk
        CHECK (btrim(granted_reason) <> ''),
    CONSTRAINT counselor_permissions_valid_period_chk
        CHECK (valid_until IS NULL OR valid_until > valid_from),
    CONSTRAINT counselor_permissions_revoke_chk
        CHECK (revoked_at IS NULL OR revoked_at >= valid_from)
);

CREATE TABLE consultation_sessions (
    session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_session_key text NOT NULL UNIQUE,
    customer_id bigint NOT NULL,
    assigned_counselor_id bigint,
    inquiry_type text NOT NULL DEFAULT 'unclassified',
    session_status text NOT NULL DEFAULT 'waiting',
    channel text NOT NULL DEFAULT 'voice',
    risk_level text NOT NULL DEFAULT 'low',
    consent_to_record boolean NOT NULL DEFAULT false,
    started_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT consultation_sessions_customer_fk
        FOREIGN KEY (customer_id) REFERENCES customers (customer_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT consultation_sessions_counselor_fk
        FOREIGN KEY (assigned_counselor_id) REFERENCES counselors (counselor_id)
        ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT consultation_sessions_external_key_length_chk
        CHECK (char_length(btrim(external_session_key)) BETWEEN 1 AND 100),
    CONSTRAINT consultation_sessions_inquiry_type_chk
        CHECK (inquiry_type IN (
            'unclassified',
            'mistaken_transfer',
            'voice_phishing_suspected',
            'lost_card',
            'overseas_payment',
            'account_opening',
            'payment_error',
            'loan',
            'general_inquiry',
            'other'
        )),
    CONSTRAINT consultation_sessions_status_chk
        CHECK (session_status IN (
            'waiting',
            'analyzing',
            'ready',
            'in_progress',
            'summarizing',
            'wrap_up',
            'completed',
            'cancelled'
        )),
    CONSTRAINT consultation_sessions_channel_chk
        CHECK (channel IN ('voice', 'chat', 'web')),
    CONSTRAINT consultation_sessions_risk_chk
        CHECK (risk_level IN ('low', 'medium', 'high', 'critical')),
    CONSTRAINT consultation_sessions_period_chk
        CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT consultation_sessions_id_customer_uk
        UNIQUE (session_id, customer_id)
);

CREATE TABLE utterances (
    utterance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL,
    speaker_type text NOT NULL,
    sequence_no integer NOT NULL,
    transcript_ciphertext bytea,
    encryption_key_version text,
    masked_transcript text NOT NULL,
    contains_sensitive_data boolean NOT NULL DEFAULT false,
    stt_confidence numeric(5,4),
    spoken_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT utterances_session_fk
        FOREIGN KEY (session_id) REFERENCES consultation_sessions (session_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT utterances_speaker_chk
        CHECK (speaker_type IN ('customer', 'system', 'counselor')),
    CONSTRAINT utterances_sequence_chk
        CHECK (sequence_no > 0),
    CONSTRAINT utterances_masked_not_blank_chk
        CHECK (btrim(masked_transcript) <> ''),
    CONSTRAINT utterances_ciphertext_pair_chk
        CHECK (
            (transcript_ciphertext IS NULL AND encryption_key_version IS NULL)
            OR (transcript_ciphertext IS NOT NULL AND encryption_key_version IS NOT NULL)
        ),
    CONSTRAINT utterances_stt_confidence_chk
        CHECK (stt_confidence IS NULL OR stt_confidence BETWEEN 0 AND 1),
    CONSTRAINT utterances_session_sequence_uk
        UNIQUE (session_id, sequence_no)
);

CREATE TABLE model_analysis_results (
    analysis_result_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL,
    result_key text NOT NULL UNIQUE,
    model_name text NOT NULL,
    model_version text NOT NULL,
    output_schema_version text NOT NULL DEFAULT '1.0',
    analysis_status text NOT NULL DEFAULT 'completed',
    emotion_temperature_score numeric(5,2),
    emotion_temperature_level text,
    voice_arousal_score numeric(5,2),
    voice_dominance_score numeric(5,2),
    voice_valence_score numeric(5,2),
    negative_activation_score numeric(5,2),
    audio_quality text NOT NULL,
    failure_code text,
    generated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT model_analysis_results_session_fk
        FOREIGN KEY (session_id) REFERENCES consultation_sessions (session_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT model_analysis_results_result_key_length_chk
        CHECK (char_length(btrim(result_key)) BETWEEN 1 AND 100),
    CONSTRAINT model_analysis_results_model_length_chk
        CHECK (
            char_length(btrim(model_name)) BETWEEN 1 AND 100
            AND char_length(btrim(model_version)) BETWEEN 1 AND 50
        ),
    CONSTRAINT model_analysis_results_schema_version_chk
        CHECK (output_schema_version ~ '^[0-9]+\.[0-9]+$'),
    CONSTRAINT model_analysis_results_status_chk
        CHECK (analysis_status IN ('completed', 'unavailable', 'failed')),
    CONSTRAINT model_analysis_results_temperature_score_chk
        CHECK (
            emotion_temperature_score IS NULL
            OR emotion_temperature_score BETWEEN 0 AND 100
        ),
    CONSTRAINT model_analysis_results_temperature_level_chk
        CHECK (
            emotion_temperature_level IS NULL
            OR emotion_temperature_level IN ('stable', 'caution', 'elevated')
        ),
    CONSTRAINT model_analysis_results_completed_payload_chk
        CHECK (
            (
                analysis_status = 'completed'
                AND emotion_temperature_score IS NOT NULL
                AND emotion_temperature_level IS NOT NULL
                AND failure_code IS NULL
            )
            OR (
                analysis_status IN ('unavailable', 'failed')
                AND emotion_temperature_score IS NULL
                AND emotion_temperature_level IS NULL
                AND voice_arousal_score IS NULL
                AND voice_dominance_score IS NULL
                AND voice_valence_score IS NULL
                AND negative_activation_score IS NULL
                AND char_length(btrim(failure_code)) BETWEEN 1 AND 100
            )
        ),
    CONSTRAINT model_analysis_results_temperature_pair_chk
        CHECK (
            analysis_status <> 'completed'
            OR (emotion_temperature_score <= 33 AND emotion_temperature_level = 'stable')
            OR (
                emotion_temperature_score > 33
                AND emotion_temperature_score <= 66
                AND emotion_temperature_level = 'caution'
            )
            OR (emotion_temperature_score > 66 AND emotion_temperature_level = 'elevated')
        ),
    CONSTRAINT model_analysis_results_arousal_chk
        CHECK (voice_arousal_score IS NULL OR voice_arousal_score BETWEEN 0 AND 100),
    CONSTRAINT model_analysis_results_dominance_chk
        CHECK (voice_dominance_score IS NULL OR voice_dominance_score BETWEEN 0 AND 100),
    CONSTRAINT model_analysis_results_valence_chk
        CHECK (voice_valence_score IS NULL OR voice_valence_score BETWEEN 0 AND 100),
    CONSTRAINT model_analysis_results_negative_activation_chk
        CHECK (negative_activation_score IS NULL OR negative_activation_score BETWEEN 0 AND 100),
    CONSTRAINT model_analysis_results_audio_quality_chk
        CHECK (audio_quality IN ('normal', 'low_volume', 'noisy', 'too_short', 'unavailable')),
    CONSTRAINT model_analysis_results_id_session_uk
        UNIQUE (analysis_result_id, session_id),
    CONSTRAINT model_analysis_results_version_generated_uk
        UNIQUE (session_id, model_name, model_version, generated_at)
);

CREATE TABLE ai_consultation_cards (
    card_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL UNIQUE,
    analysis_result_id bigint,
    card_schema_version text NOT NULL DEFAULT '1.0',
    summary text NOT NULL,
    customer_request text,
    keywords text[] NOT NULL DEFAULT ARRAY[]::text[],
    risk_factors text[] NOT NULL DEFAULT ARRAY[]::text[],
    urgency_level text NOT NULL,
    risk_level text NOT NULL,
    related_manual_refs text[] NOT NULL DEFAULT ARRAY[]::text[],
    suggested_opening text,
    recommended_actions text[] NOT NULL DEFAULT ARRAY[]::text[],
    confirmation_items text[] NOT NULL DEFAULT ARRAY[]::text[],
    confirmation_status text NOT NULL DEFAULT 'pending',
    confirmed_at timestamptz,
    model_name text NOT NULL,
    model_version text NOT NULL,
    generated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ai_consultation_cards_session_fk
        FOREIGN KEY (session_id) REFERENCES consultation_sessions (session_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ai_consultation_cards_analysis_result_fk
        FOREIGN KEY (analysis_result_id, session_id)
        REFERENCES model_analysis_results (analysis_result_id, session_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ai_consultation_cards_schema_version_chk
        CHECK (card_schema_version ~ '^[0-9]+\.[0-9]+$'),
    CONSTRAINT ai_consultation_cards_summary_not_blank_chk
        CHECK (btrim(summary) <> ''),
    CONSTRAINT ai_consultation_cards_customer_request_chk
        CHECK (customer_request IS NULL OR btrim(customer_request) <> ''),
    CONSTRAINT ai_consultation_cards_urgency_chk
        CHECK (urgency_level IN ('low', 'medium', 'high', 'critical')),
    CONSTRAINT ai_consultation_cards_risk_chk
        CHECK (risk_level IN ('low', 'medium', 'high', 'critical')),
    CONSTRAINT ai_consultation_cards_confirmation_status_chk
        CHECK (confirmation_status IN ('pending', 'confirmed', 'correction_requested')),
    CONSTRAINT ai_consultation_cards_confirmation_time_chk
        CHECK (
            (confirmation_status = 'confirmed' AND confirmed_at IS NOT NULL)
            OR (confirmation_status <> 'confirmed' AND confirmed_at IS NULL)
        ),
    CONSTRAINT ai_consultation_cards_model_not_blank_chk
        CHECK (btrim(model_name) <> '' AND btrim(model_version) <> '')
);

