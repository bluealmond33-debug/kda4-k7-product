-- 감사로그는 생성 후 변경·삭제할 수 없도록 한다.
CREATE OR REPLACE FUNCTION prevent_access_log_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'access_logs rows are immutable';
END;
$$;

CREATE TRIGGER trg_access_logs_immutable
BEFORE UPDATE OR DELETE ON access_logs
FOR EACH ROW EXECUTE FUNCTION prevent_access_log_mutation();

