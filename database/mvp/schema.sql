                OR (emotion_score > 66 AND emotion_level = 'elevated')
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'calls'
          AND column_name = 'auth_verified'
